function utmFixed(url, skill) {
  const hashAt = url.indexOf('#');
  const hash = hashAt >= 0 ? url.slice(hashAt) : '';
  const noHash = hashAt >= 0 ? url.slice(0, hashAt) : url;
  const qAt = noHash.indexOf('?');
  const base = qAt >= 0 ? noHash.slice(0, qAt) : noHash;
  const params = (qAt >= 0 ? noHash.slice(qAt + 1).split(/&(?:amp;)?/) : []).filter(Boolean).filter((p) => !/^utm_(source|medium|content)=/.test(p));
  for (const [k, v] of UTM(skill)) params.push(`${k}=${encodeURIComponent(v)}`);
  return `${base}?${params.join('&')}${hash}`;
}
function utmOk(url, skill) {
  const hashAt = url.indexOf('#');
  const noHash = hashAt >= 0 ? url.slice(0, hashAt) : url;
  const q = noHash.includes('?') ? noHash.slice(noHash.indexOf('?') + 1) : '';
  const params = new Map(q.split(/&(?:amp;)?/).filter(Boolean).map((p) => { const [k, ...v] = p.split('='); return [k, decodeURIComponent(v.join('='))]; }));
  return UTM(skill).every(([k, v]) => params.get(k) === v);
}

