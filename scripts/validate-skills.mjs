// Module names that are also everyday words (data.model, node.type, size.width): in prose they are pair-checked
// only when written as a call or on the editor (`editor.data.x`, `data.x()`).
const GENERIC_MODULE_WORDS = new Set(['data', 'node', 'size', 'core', 'keys', 'position', 'refresh', 'format', 'language', 'icon', 'file', 'url', 'save', 'print', 'help', 'spaces', 'markers', 'clean', 'helpers', 'tooltip', 'toast', 'modals', 'snapshot', 'entities', 'forms', 'quote', 'lists', 'align', 'colors', 'video', 'link', 'table', 'image']);
function identifierExists(raw) {
  const onEditor = /^(?:editor|this|getEditor\(\))\??\./.test(raw);
  const isCall = /\(\)$/.test(raw);
  const name = raw.replace(/\(\)$/, '').replace(/^(?:editor|this|getEditor\(\))\??\./, '');
  if (invalidNames.has(raw) || invalidNames.has(name)) return true; // prose only (code is checked separately)
  if (allowAny.has(raw) || allowAny.has(name) || fileNames.has(name)) return true;
  if (/^metadata\./.test(name)) return true; // refers to the skill's own frontmatter
  if (name.includes('.')) {
    if (strings.has(name)) return true; // event names such as 'image.beforeUpload'
    const segs = name.split('.');
    let pair = segs.length >= 2 ? modulePair(segs[0], segs[1]) : null;
    if (pair === false && !isCall && segs[0] === 'events' && strings.has(segs[1])) pair = true; // `events.initialized`: a key of the events option
    if (pair === false && GENERIC_MODULE_WORDS.has(segs[0]) && !onEditor && !isCall) pair = null;
    if (pair === false) return false;
    return segs.every((seg) => tokens.has(seg) || wrapperTokens.has(seg) || allowAny.has(seg));
  }
  return existsInFroala(name) || wrapperTokens.has(name);
}

