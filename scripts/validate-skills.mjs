// The agent-run project checker: scripts/check-froala.mjs is copied into each skill that tells agents to run it
// (skills are installed one by one, so each needs its own copy). The copy does not depend on the Froala version.
const checkerCopy = (() => {
  const src = fs.readFileSync(CHECKER_SOURCE, 'utf8');
  const nl = src.indexOf('\n');
  return `${src.slice(0, nl + 1)}${CHECKER_MARK}\n${src.slice(nl + 1)}`;
})();
