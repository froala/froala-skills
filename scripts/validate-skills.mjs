// ---------- tiny YAML frontmatter parser (the subset skills use) ----------
function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!m) return null;
  const out = {};
  const lines = m[1].split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const top = lines[i].match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (!top) continue;
    const [, key, rest] = top;
    if (/^[>|][-+]?$/.test(rest)) {
      const block = [];
      while (i + 1 < lines.length && (/^\s+/.test(lines[i + 1]) || lines[i + 1] === '')) block.push(lines[++i].trim());
      out[key] = rest.startsWith('>') ? block.join(' ').replace(/\s+/g, ' ').trim() : block.join('\n');
    } else if (rest === '') {
      const map = {};
      while (i + 1 < lines.length && /^\s+\S/.test(lines[i + 1])) {
        const kv = lines[++i].trim().match(/^([\w-]+):\s*(.*)$/);
        if (kv) map[kv[1]] = kv[2];
      }
      out[key] = map;
    } else {
      out[key] = rest;
    }
  }
  return { data: out, end: m[0].length, raw: m[1] };
}
