// Every closed js/javascript/mjs/cjs/json code block must parse. JavaScript is compiled (never run) as an ES module
// and, failing that, as a classic script, in one child process (vm.SourceTextModule needs --experimental-vm-modules).
if (parseBlocks.length) {
  // JSX in a block labelled js: markup outside string literals (HTML inside strings does not count)
  const looksLikeJsx = (code) => /<\/[A-Za-z]|\/>|<[A-Z][\w.]*[\s>]/.test(code.replace(/'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|`(?:\\.|[^`\\])*`/g, "''"));
  const js = parseBlocks.filter((b) => b.lang !== 'json');
  const PARSER = `import vm from 'node:vm'; import fs from 'node:fs';
const out = JSON.parse(fs.readFileSync(0, 'utf8')).map((code) => {
  let message;
  try { new vm.SourceTextModule(code); return null; } catch (e) { message = e.message; }
  try { new vm.Script(code); return null; } catch {}
  // an options fragment (\`height: 300, events: { ... },\`) is checked as the body of an object literal
  try { new vm.SourceTextModule('({\\n' + code + '\\n})'); return null; } catch {}
  try { new vm.Script('({\\n' + code + '\\n})'); return null; } catch {}
  return message;
});
process.stdout.write(JSON.stringify(out));`;
  let results = null;
  try {
    results = JSON.parse(execFileSync(process.execPath, ['--experimental-vm-modules', '--no-warnings', '--input-type=module', '-e', PARSER], { input: JSON.stringify(js.map((b) => b.code)), encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));
  } catch (e) {
    warn(null, 0, `The code-block parse check could not run: ${firstLine(e)}`);
  }
  const failures = [];
  if (results) js.forEach((b, i) => { if (results[i] && !looksLikeJsx(b.code)) failures.push({ ...b, message: results[i] }); });
  for (const b of parseBlocks.filter((x) => x.lang === 'json')) {
    try {
      JSON.parse(b.code);
    } catch (e) {
      try {
        JSON.parse(`{${b.code}}`); // a fragment of members ("styles": [...], "x": ...) is checked as the body of an object
        continue;
      } catch {
        /* report the original error */
      }
      const pos = Number((e.message.match(/position (\d+)/) || [])[1]);
      const lineMatch = e.message.match(/line (\d+)/);
      const rel = lineMatch ? Number(lineMatch[1]) : Number.isFinite(pos) ? b.code.slice(0, pos).split('\n').length : 1;
      error(b.file, b.line + rel - 1, `JSON code block does not parse: ${e.message.replace(/\s*\(line \d+ column \d+\)$/, '')}. Fix it, or mark an intentional fragment with \`\`\`json fragment`);
    }
  }
  if (failures.length) {
    // node --check gives the line of the error
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'froala-parse-'));
    try {
      failures.forEach((b, i) => {
        let rel = 1;
        const f = path.join(tmp, `block${i}.mjs`);
        fs.writeFileSync(f, b.code);
        try {
          execFileSync(process.execPath, ['--check', f], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
        } catch (e) {
          const m = String(e.stderr || '').match(/block\d+\.mjs:(\d+)/);
          if (m) rel = Number(m[1]);
        }
        error(b.file, b.line + rel - 1, `Code block does not parse as JavaScript: ${b.message}. Fix it, or mark an intentional fragment with \`\`\`js fragment`);
      });
    } finally {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
  }
}

// 4. repo-level consistency: versions and skill lists (only when checking a repo, not a bare skills folder)
if (REPO_ROOT) {
  const readJson = (p) => {
    try {
      return JSON.parse(fs.readFileSync(p, 'utf8'));
    } catch (e) {
      error(p, 1, `Could not parse JSON: ${e.message}`);
      return null;
    }
  };
  const versions = []; // [where, file, version]
  for (const f of ['plugin.json', '.claude-plugin/plugin.json', '.cursor-plugin/plugin.json']) {
    const p = path.join(REPO_ROOT, f);
    if (!fs.existsSync(p)) { if (f !== '.cursor-plugin/plugin.json') error(p, 0, 'Missing manifest'); continue; }
    const j = readJson(p);
    if (j) versions.push([f, p, j.version]);
  }
  const mpPath = path.join(REPO_ROOT, '.claude-plugin', 'marketplace.json');
  if (fs.existsSync(mpPath)) {
    const mp = readJson(mpPath);
    const entries = (mp && mp.plugins) || [];
    const entry = entries.find((e) => e.source === '.' || e.source === './') || entries[0];
    if (!entry) error(mpPath, 1, 'marketplace.json has no plugin entry');
    else versions.push([`.claude-plugin/marketplace.json (plugin "${entry.name}")`, mpPath, entry.version]);
  } else error(mpPath, 0, 'Missing manifest');
  const clPath = path.join(REPO_ROOT, 'CHANGELOG.md');
  if (fs.existsSync(clPath)) {
    const m = fs.readFileSync(clPath, 'utf8').match(/^##\s+\[?v?(\d+\.\d+\.\d+)/m);
    if (m) versions.push(['CHANGELOG.md (top entry)', clPath, m[1]]);
    else error(clPath, 1, 'CHANGELOG.md has no "## x.y.z" entry');
  } else error(clPath, 0, 'Missing CHANGELOG.md');
  for (const [skill, v] of skillVersions) versions.push([`skills/${skill} metadata.version`, path.join(SKILLS_DIR, skill, 'SKILL.md'), v]);
  const counts = new Map();
  for (const [, , v] of versions) counts.set(v, (counts.get(v) || 0) + 1);
  if (counts.size > 1) {
    const expected = [...counts].sort((a, b) => b[1] - a[1] || (older(semver(String(a[0])), semver(String(b[0]))) ? 1 : -1))[0][0];
    for (const [where, file, v] of versions) if (v !== expected) error(file, 1, `Version mismatch: ${where} is ${v}, but most of the repo says ${expected}. plugin.json, .claude-plugin/plugin.json, marketplace.json, every skill's metadata.version and the top CHANGELOG entry must match.`);
  }

  const expected = new Set(skillDirs.filter((s) => fs.existsSync(path.join(SKILLS_DIR, s, 'SKILL.md'))));
  const SKILL_NAME = /^[a-z0-9]+(?:-[a-z0-9]+)+$/;
  const compare = (file, label, listed) => {
    if (!fs.existsSync(file)) { error(file, 0, `Missing ${label}`); return; }
    for (const s of expected) if (!listed.has(s)) error(file, 0, `Skill "${s}" is missing from ${label}`);
    for (const s of listed) if (!expected.has(s)) error(file, 0, `${label} lists "${s}", which is not a folder in skills/`);
  };
  const readme = path.join(REPO_ROOT, 'README.md');
  compare(readme, 'the README skill list', new Set(fs.existsSync(readme) ? [...fs.readFileSync(readme, 'utf8').matchAll(/^###\s+`([a-z0-9-]+)`\s*$/gm)].map((m) => m[1]).filter((s) => SKILL_NAME.test(s)) : []));
  const pd = path.join(REPO_ROOT, 'PLUGIN_DESCRIPTION.md');
  compare(pd, 'the PLUGIN_DESCRIPTION.md skill table', new Set(fs.existsSync(pd) ? [...fs.readFileSync(pd, 'utf8').matchAll(/^\|\s*`([a-z0-9-]+)`\s*\|/gm)].map((m) => m[1]).filter((s) => SKILL_NAME.test(s)) : []));
  const ss = path.join(REPO_ROOT, 'skills.sh.json');
  const ssJson = fs.existsSync(ss) ? readJson(ss) : null;
  compare(ss, 'skills.sh.json groupings', new Set(((ssJson && ssJson.groupings) || []).flatMap((g) => g.skills || [])));
  const fb = path.join(REPO_ROOT, '.github', 'ISSUE_TEMPLATE', 'skill-feedback.yml');
  let fbSkills = new Set();
  if (fs.existsSync(fb)) {
    const y = fs.readFileSync(fb, 'utf8');
    const blockStart = y.search(/^\s*id:\s*skill\s*$/m);
    if (blockStart >= 0) {
      const rest = y.slice(blockStart);
      const nextItem = rest.slice(1).search(/^\s*-\s+type:/m);
      const block = nextItem >= 0 ? rest.slice(0, nextItem + 1) : rest;
      fbSkills = new Set([...block.matchAll(/^\s*-\s+["']?([a-z0-9-]+)["']?\s*$/gm)].map((m) => m[1]).filter((s) => SKILL_NAME.test(s)));
    } else error(fb, 1, 'No "id: skill" dropdown found');
  }
  compare(fb, 'the skill-feedback issue template', fbSkills);
}

