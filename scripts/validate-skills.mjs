#!/usr/bin/env node
// Validates the Froala agent skills against the published npm packages.
//
//   node scripts/validate-skills.mjs                    check against the version the skills declare (metadata.verified_against)
//   node scripts/validate-skills.mjs --froala latest    check against the latest froala-editor on npm
//   node scripts/validate-skills.mjs --froala 5.5.0     check against a specific version
//   node scripts/validate-skills.mjs --skills-dir <dir> check another skills folder (used by the negative tests)
//   node scripts/validate-skills.mjs --write            regenerate references/plugin-names.md
//   node scripts/validate-skills.mjs --strict-version   fail when a skill was verified against an older release
//   node scripts/validate-skills.mjs --check-links      also fetch every froala.com link (warnings only)
//
// What it checks: frontmatter, version metadata, hard-coded versions, toolbar buttons, events, option keys,
// pluginsEnabled/pluginsDisabled values, editor.<module>.<method>() calls, inline API names, and the
// generated plugin table. What it cannot check: whether an example behaves correctly at runtime.
//
// Needs Node 18+, npm and tar. No npm dependencies.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argvEarly = process.argv.slice(2);
const SKILLS_DIR = argvEarly.includes('--skills-dir') ? path.resolve(argvEarly[argvEarly.indexOf('--skills-dir') + 1]) : path.join(ROOT, 'skills');
const ALLOWLIST = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'validate-allowlist.json'), 'utf8'));
const GENERATED_MARK = '<!-- generated by scripts/validate-skills.mjs';
const SPEC_KEYS = new Set(['name', 'description', 'license', 'compatibility', 'metadata', 'allowed-tools']);
const WRAPPERS = ['react-froala-wysiwyg', 'vue-froala-wysiwyg', 'angular-froala-wysiwyg', 'svelte-froala-wysiwyg'];
const PLUGIN_NAMES_TARGETS = ['froala-initialization-and-sdks', 'froala-error-diagnosis', 'froala-migrate'];

// ---------- arguments ----------
const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const option = (name, fallback) => {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback;
};
const WRITE = flag('--write');
const STRICT_VERSION = flag('--strict-version');
const CHECK_LINKS = flag('--check-links');
let froalaVersion = option('--froala', 'declared');

// ---------- reporting ----------
const errors = [];
const warnings = [];
const inActions = !!process.env.GITHUB_ACTIONS;
const rel = (f) => path.relative(ROOT, f);
function report(list, kind, file, line, msg) {
  list.push({ file: file ? rel(file) : '', line, msg });
  if (inActions) console.log(`::${kind} file=${file ? rel(file) : ''},line=${line || 1}::${msg}`);
}
const error = (file, line, msg) => report(errors, 'error', file, line, msg);
const warn = (file, line, msg) => report(warnings, 'warning', file, line, msg);
const lineOf = (text, index) => text.slice(0, index).split('\n').length;

// ---------- download packages ----------
const sh = (cmd, args, opts = {}) => execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts }).trim();
if (froalaVersion === 'declared') {
  // Pull requests are checked against the version the skills say they were verified against.
  const declared = new Set();
  for (const d of fs.readdirSync(SKILLS_DIR, { withFileTypes: true })) {
    const f = path.join(SKILLS_DIR, d.name, 'SKILL.md');
    if (!d.isDirectory() || !fs.existsSync(f)) continue;
    const m = fs.readFileSync(f, 'utf8').match(/verified_against:\s*"?froala-editor (\d+\.\d+\.\d+)/);
    if (m) declared.add(m[1]);
  }
  if (declared.size !== 1) {
    console.log(`ERROR    skills declare ${declared.size ? [...declared].join(', ') : 'no'} verified_against version(s); expected exactly one`);
    process.exit(1);
  }
  froalaVersion = [...declared][0];
}
if (froalaVersion === 'latest') froalaVersion = sh('npm', ['view', 'froala-editor', 'version']);
const cache = path.join(os.tmpdir(), `froala-validate-${froalaVersion}`);
function fetchPackage(name, version) {
  const dir = path.join(cache, name.replace('/', '__'));
  if (fs.existsSync(path.join(dir, 'package', 'package.json'))) return path.join(dir, 'package');
  fs.mkdirSync(dir, { recursive: true });
  const tgz = sh('npm', ['pack', `${name}@${version}`, '--silent', '--pack-destination', dir]).split('\n').pop();
  sh('tar', ['-xzf', path.join(dir, tgz), '-C', dir]);
  return path.join(dir, 'package');
}
console.log(`Checking skills against froala-editor ${froalaVersion}`);
const froalaDir = fetchPackage('froala-editor', froalaVersion);
const wrapperDirs = WRAPPERS.map((w) => {
  try {
    return fetchPackage(w, froalaVersion);
  } catch {
    error(null, 0, `Could not download ${w}@${froalaVersion}; required to check wrapper identifiers`);
    return null;
  }
}).filter(Boolean);

// ---------- index what really exists ----------
function readJsFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (['node_modules', 'languages', 'demo'].includes(entry.name)) continue;
      out.push(...readJsFiles(p));
    } else if (/\.(m?js|jsx|ts|svelte|vue)$/.test(entry.name) && !entry.name.endsWith('.map')) {
      out.push({ path: p, text: fs.readFileSync(p, 'utf8') });
    }
  }
  return out;
}
const froalaFiles = readJsFiles(path.join(froalaDir, 'js'));
const froalaSource = froalaFiles.map((f) => f.text).join('\n');
const wrapperSource = wrapperDirs.map((d) => readJsFiles(d).map((f) => f.text).join('\n')).join('\n');

const tokens = new Set(froalaSource.match(/[A-Za-z_$][\w$]*/g));
const wrapperTokens = new Set(wrapperSource.match(/[A-Za-z_$][\w$]*/g));
// Exact quoted-string lookup. (A regex that pairs quotes across a minified file drifts and gives false results.)
const stringCache = new Map();
const strings = {
  has(name) {
    if (!stringCache.has(name)) {
      stringCache.set(name, froalaSource.includes(`"${name}"`) || froalaSource.includes(`'${name}'`) || froalaSource.includes(`\`${name}\``));
    }
    return stringCache.get(name);
  },
};
const commands = new Set();
for (const m of froalaSource.matchAll(/RegisterCommand\(\s*["']([^"']+)["']/g)) commands.add(m[1]);
for (const m of froalaSource.matchAll(/[{,]([A-Za-z_]\w*):\{title:"/g)) commands.add(m[1]);

// plugin file -> registered plugins and modules, commands, and presence in EACH bundle
const bundleText = {
  pkgd: fs.readFileSync(path.join(froalaDir, 'js', 'froala_editor.pkgd.min.js'), 'utf8'),
  pluginsPkgd: fs.readFileSync(path.join(froalaDir, 'js', 'plugins.pkgd.min.js'), 'utf8'),
};
const pluginRegex = /PLUGINS\.([A-Za-z_]\w*)\s*=\s*function/g;
const moduleRegex = /MODULES\.([A-Za-z_]\w*)\s*=\s*function/g;
const coreModules = new Set([...fs.readFileSync(path.join(froalaDir, 'js', 'froala_editor.min.js'), 'utf8').matchAll(moduleRegex)].map((m) => m[1]));
const registeredIn = (text, kind, name) => text.includes(`${kind}.${name}=function`) || new RegExp(`${kind}\\.${name}\\s*=\\s*function`).test(text);
const allPluginNames = new Set();
const pluginRows = [];
for (const sub of ['plugins', 'third_party']) {
  const dir = path.join(froalaDir, 'js', sub);
  if (!fs.existsSync(dir)) continue;
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.min.js')).sort()) {
    const text = fs.readFileSync(path.join(dir, file), 'utf8');
    const plugins = [...new Set([...text.matchAll(pluginRegex)].map((m) => m[1]))];
    const modules = [...new Set([...text.matchAll(moduleRegex)].map((m) => m[1]))].filter((n) => !coreModules.has(n));
    plugins.forEach((n) => allPluginNames.add(n));
    const cmds = [...new Set([...text.matchAll(/RegisterCommand\(\s*["']([^"']+)["']/g)].map((m) => m[1]))];
    const entries = [...plugins.map((n) => ['PLUGINS', n]), ...modules.map((n) => ['MODULES', n])];
    const inBundle = (t) => entries.length > 0 && entries.every(([kind, n]) => registeredIn(t, kind, n));
    pluginRows.push({ file: `js/${sub}/${file}`, plugins, modules, cmds, inPkgd: inBundle(bundleText.pkgd), inPluginsPkgd: inBundle(bundleText.pluginsPkgd) });
  }
}

// file and folder names (agents are told to load e.g. track_changes.min.js or js/third_party/)
const fileNames = new Set(['plugins', 'third_party']);
for (const r of pluginRows) fileNames.add(path.basename(r.file).replace(/\.min\.js$/, ''));

