// ---------- markdown helpers ----------
function lineIndex(text) {
  const starts = [0];
  for (let i = 0; i < text.length; i++) if (text[i] === '\n') starts.push(i + 1);
  return (index) => {
    let lo = 0;
    let hi = starts.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (starts[mid] <= index) lo = mid;
      else hi = mid - 1;
    }
    return lo + 1;
  };
}
// CommonMark-style fenced code blocks: ``` or ~~~ (3+), optional info string, closed by the same character
// repeated at least as many times on a line of its own. An unclosed fence runs to the end of the file.
function parseFences(text) {
  const fences = [];
  const re = /^.*$/gm;
  let open = null;
  for (let m = re.exec(text); m; m = re.exec(text)) {
    if (m[0] === '' && m.index === text.length) break;
    const line = m[0].replace(/\r$/, '');
    if (!open) {
      const o = line.match(/^(\s*)(`{3,}|~{3,})(.*)$/);
      if (o && !(o[2][0] === '`' && o[3].includes('`'))) {
        const info = o[3].trim();
        open = { start: m.index, char: o[2][0], len: o[2].length, info, lang: (info.split(/\s+/)[0] || '').replace(/^\{\.?|\}$/g, '').toLowerCase(), codeStart: m.index + m[0].length + 1 };
      }
    } else {
      const c = line.match(/^\s*(`{3,}|~{3,})\s*$/);
      if (c && c[1][0] === open.char && c[1].length >= open.len) {
        fences.push({ ...open, end: m.index + m[0].length, code: text.slice(open.codeStart, m.index), closed: true });
        open = null;
      }
    }
    if (re.lastIndex === m.index) re.lastIndex++;
  }
  if (open) fences.push({ ...open, end: text.length, code: text.slice(Math.min(open.codeStart, text.length)), closed: false });
  return fences;
}
const blank = (s) => s.replace(/[^\n]/g, ' ');
function skipRegions(body) {
  return [...body.matchAll(/<!-- validate:skip -->[\s\S]*?<!-- validate:end -->/g)].map((r) => [r.index, r.index + r[0].length]);
}
// Mapping tables (e.g. TinyMCE -> Froala) contain other products' identifiers. In a table that has a
// column whose header mentions "Froala", only that column is checked; the other cells are masked.
// Prose between <!-- validate:skip --> and <!-- validate:end --> is not checked either.
function maskForProse(body, regions) {
  let out = body;
  for (const [a, b] of regions) out = out.slice(0, a) + blank(out.slice(a, b)) + out.slice(b);
  const lines = out.split('\n');
  for (let i = 0; i < lines.length - 1; i++) {
    if (!/^\s*\|.*\|\s*$/.test(lines[i]) || !/^\s*\|[\s:|-]+\|\s*$/.test(lines[i + 1])) continue;
    const header = lines[i].split('|');
    const froalaCol = header.findIndex((c) => /froala/i.test(c));
    if (froalaCol < 0) continue;
    lines[i] = blank(lines[i]);
    let j = i + 2;
    for (; j < lines.length && /^\s*\|/.test(lines[j]); j++) {
      const cells = lines[j].split('|');
      lines[j] = cells.map((c, k) => (k === froalaCol ? c : blank(c))).join(' ');
    }
    i = j - 1;
  }
  return lines.join('\n');
}

