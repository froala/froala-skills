// Validates the Froala agent skills against the published npm packages.
//
//   node scripts/validate-skills.mjs                    check against the version the skills declare (metadata.verified_against)
//   node scripts/validate-skills.mjs --froala latest    check against the latest froala-editor on npm
//   node scripts/validate-skills.mjs --froala 5.5.0     check against a specific version
//   node scripts/validate-skills.mjs --skills-dir <dir> check another skills folder (no repo-level checks)
//   node scripts/validate-skills.mjs --repo-root <dir>  check another repo (its skills/ plus manifests and skill lists)
//   node scripts/validate-skills.mjs --allowlist <file> use another allowlist (used by the tests)
//   node scripts/validate-skills.mjs --write            regenerate references/plugin-names.md and the scripts/check-froala.mjs copies
//   node scripts/validate-skills.mjs --fix-utm          add the froala-skills UTM parameters to froala.com docs links, in place
//   node scripts/validate-skills.mjs --strict-version   fail when a skill was verified against an older release
//   node scripts/validate-skills.mjs --check-links      also fetch every froala.com link (warnings only)
//
// What it checks:
//   - frontmatter (spec keys, name, description length and identifier tokens, license, metadata.*), SKILL.md line budget
//   - hard-coded froala-editor versions (CDN, npm specifiers, package.json snippets)
//   - toolbar buttons (flat, grouped and object forms), events, option keys, pluginsEnabled/pluginsDisabled values,
//     <receiver>.<module>.<method>() pairs (indexed from the package source), FroalaEditor.<Static> names,
//     inline API names in prose
//   - relative links and references/*.md paths (must stay inside the skill), UTM parameters on docs links
//   - js/javascript/mjs/cjs/json code blocks parse (compiled, never run; ```js fragment opts a block out)
//   - the generated plugin table and check-froala.mjs copies, and (repo mode) manifest/CHANGELOG/skill version sync
//     and skill lists
// What it cannot check: whether an example behaves correctly at runtime.
//
// Needs Node 22+, npm and tar. No npm dependencies.

