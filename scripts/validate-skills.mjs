// ---------- tiny YAML frontmatter parser (the subset skills use) ----------
function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return null;
  const out = {};
  const lines = m[1].split('\n');
  for (let i = 0; i < lines.length; i++) {
    const top = lines[i].match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (!top) continue;
    const [, key, rest] = top;
    if (rest === '>' || rest === '|' || rest === '>-' || rest === '|-') {
      const block = [];
      while (i + 1 < lines.length && /^\s+/.test(lines[i + 1])) block.push(lines[++i].trim());
      out[key] = rest.startsWith('>') ? block.join(' ') : block.join('\n');
    } else if (rest === '') {
      const map = {};
      while (i + 1 < lines.length && /^\s+\S/.test(lines[i + 1])) {
        const kv = lines[++i].trim().match(/^([\w-]+):\s*(.*)$/);
        if (kv) map[kv[1]] = kv[2];
      }
      out[key] = map;
    } else {
      out[key] = rest;
    }
  }
  return { data: out, end: m[0].length };
}
const unquote = (v) => (typeof v === 'string' ? v.replace(/^["']|["']$/g, '') : v);
const semver = (v) => (v.match(/(\d+)\.(\d+)\.(\d+)/) || []).slice(1).map(Number);
const older = (a, b) => {
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] < b[i];
  return false;
};

// ---------- JS snippet helpers ----------
function matchBrace(text, open) {
  // returns index of the matching closing brace, skipping strings and comments
  const pairs = { '{': '}', '[': ']', '(': ')' };
  const stack = [];
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === '"' || c === "'" || c === '`') {
      for (i++; i < text.length && text[i] !== c; i++) if (text[i] === '\\') i++;
      continue;
    }
    if (c === '/' && text[i + 1] === '/') { while (i < text.length && text[i] !== '\n') i++; continue; }
    if (c === '/' && text[i + 1] === '*') { i = text.indexOf('*/', i + 2) + 1; if (i === 0) return -1; continue; }
    if (pairs[c]) stack.push(pairs[c]);
    else if (c === stack[stack.length - 1]) { stack.pop(); if (!stack.length) return i; }
  }
  return -1;
}
function topLevelKeys(text, open) {
  // keys of the object literal whose "{" is at index `open`
  const close = matchBrace(text, open);
  if (close < 0) return [];
  const keys = [];
  let depth = 0;
  let expectKey = true;
  for (let i = open + 1; i < close; i++) {
    const c = text[i];
    if (c === '"' || c === "'" || c === '`') {
      const q = c;
      const start = i;
      for (i++; i < close && text[i] !== q; i++) if (text[i] === '\\') i++;
      if (depth === 0 && expectKey && q !== '`') {
        const after = text.slice(i + 1).match(/^\s*([:(])/);
        if (after) keys.push({ key: text.slice(start + 1, i), index: start });
        expectKey = false;
      }
      continue;
    }
    if (c === '/' && text[i + 1] === '/') { while (i < close && text[i] !== '\n') i++; continue; }
    if (c === '/' && text[i + 1] === '*') { i = text.indexOf('*/', i + 2) + 1; continue; }
    if ('{[('.includes(c)) { depth++; expectKey = false; continue; }
    if ('}])'.includes(c)) { depth--; continue; }
    if (depth === 0 && c === ',') { expectKey = true; continue; }
    if (depth === 0 && expectKey && /[A-Za-z_$]/.test(c)) {
      const m = text.slice(i).match(/^(?:async\s+)?([A-Za-z_$][\w$]*)\s*([:(])/);
      if (m) keys.push({ key: m[1], index: i + m[0].indexOf(m[1]) });
      expectKey = false;
    }
    if (depth === 0 && c === '.' && text.slice(i, i + 3) === '...') expectKey = false;
  }
  return keys;
}

// ---------- markdown masking ----------
// Mapping tables (e.g. TinyMCE -> Froala) contain other products' identifiers. In a table that has a
// column whose header mentions "Froala", only that column is checked; the other cells are masked.
// Prose between <!-- validate:skip --> and <!-- validate:end --> is not checked either.
function maskForProse(body) {
  const blank = (s) => s.replace(/[^\n]/g, ' ');
  let out = body.replace(/<!-- validate:skip -->[\s\S]*?<!-- validate:end -->/g, blank);
  const lines = out.split('\n');
  for (let i = 0; i < lines.length - 1; i++) {
    if (!/^\s*\|.*\|\s*$/.test(lines[i]) || !/^\s*\|[\s:|-]+\|\s*$/.test(lines[i + 1])) continue;
    const header = lines[i].split('|');
    const froalaCol = header.findIndex((c) => /froala/i.test(c));
    if (froalaCol < 0) continue;
    lines[i] = blank(lines[i]);
    let j = i + 2;
    for (; j < lines.length && /^\s*\|/.test(lines[j]); j++) {
      const cells = lines[j].split('|');
      lines[j] = cells.map((c, k) => (k === froalaCol ? c : blank(c))).join(' ');
    }
    i = j - 1;
  }
  return lines.join('\n');
}

// ---------- checks ----------
const allow = new Set(ALLOWLIST.external.map((e) => e.name));
// Names that skills mention only to say they are WRONG (e.g. licenseKey). Allowed in prose, never in code.
const invalidNames = new Set(ALLOWLIST.intentionallyInvalid.map((e) => e.name));
const existsInFroala = (name) => tokens.has(name) || strings.has(name);
function identifierExists(raw) {
  const name = raw.replace(/\(\)$/, '').replace(/^editor\./, '').replace(/^this\./, '');
  if (invalidNames.has(raw) || invalidNames.has(name)) return true; // prose only (code is checked separately)
  if (allow.has(raw) || allow.has(name) || fileNames.has(name)) return true;
  if (/^metadata\./.test(name)) return true; // refers to the skill's own frontmatter
  if (existsInFroala(name) || wrapperTokens.has(name)) return true;
  if (name.includes('.')) {
    if (strings.has(name)) return true; // event names such as 'image.beforeUpload'
    return name.split('.').every((seg) => tokens.has(seg) || wrapperTokens.has(seg) || allow.has(seg));
  }
  return false;
}

const skillDirs = fs.readdirSync(SKILLS_DIR, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
const versionsSeen = new Set();
const links = new Map();

for (const skill of skillDirs) {
  const dir = path.join(SKILLS_DIR, skill);
  const skillFile = path.join(dir, 'SKILL.md');
  if (!fs.existsSync(skillFile)) { error(dir, 0, 'Missing SKILL.md'); continue; }

  // 1. frontmatter
  const text = fs.readFileSync(skillFile, 'utf8');
  const fm = parseFrontmatter(text);
  if (!fm) { error(skillFile, 1, 'Missing YAML frontmatter'); continue; }
  const d = fm.data;
  for (const key of Object.keys(d)) if (!SPEC_KEYS.has(key)) error(skillFile, 1, `Frontmatter key "${key}" is not in the Agent Skills spec (put it under metadata:)`);
  if (!d.name) error(skillFile, 1, 'Missing name');
  else {
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(d.name) || d.name.length > 64) error(skillFile, 1, `Invalid name "${d.name}"`);
    if (d.name !== skill) error(skillFile, 1, `name "${d.name}" must match the folder "${skill}"`);
  }
  if (!d.description) error(skillFile, 1, 'Missing description');
  else if (d.description.length > 1024) error(skillFile, 1, `Description is ${d.description.length} characters (max 1024)`);
  const meta = d.metadata || {};
  const verified = unquote(meta.verified_against || '');
  if (!verified) error(skillFile, 1, 'metadata.verified_against is missing (e.g. "froala-editor 5.5.0")');
  else {
    versionsSeen.add(verified);
    const v = semver(verified);
    if (v.length === 3 && older(v, semver(froalaVersion))) {
      const msg = `Verified against ${verified}, but froala-editor ${froalaVersion} is out. Re-check the skill, then update metadata.verified_against and last_validated.`;
      STRICT_VERSION ? error(skillFile, 1, msg) : warn(skillFile, 1, msg);
    }
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(unquote(meta.last_validated || ''))) error(skillFile, 1, 'metadata.last_validated must be a YYYY-MM-DD date');

  // 2. every markdown file of the skill
  const mdFiles = [skillFile];
  const refDir = path.join(dir, 'references');
  if (fs.existsSync(refDir)) for (const f of fs.readdirSync(refDir)) if (f.endsWith('.md')) mdFiles.push(path.join(refDir, f));

  for (const file of mdFiles) {
    const body = fs.readFileSync(file, 'utf8');
    if (body.startsWith(GENERATED_MARK)) continue;

    // hard-coded versions
    for (const m of body.matchAll(/froala-editor@(\d+\.\d+\.\d+|latest)/g)) {
      error(file, lineOf(body, m.index), `Hard-coded "froala-editor@${m[1]}". Use "@VERSION" and tell the agent to use the installed version.`);
    }

    // links
    for (const m of body.matchAll(/https:\/\/(?:www\.)?froala\.com\/[^\s)>\]"'`]+/g)) {
      if (!links.has(m[0])) links.set(m[0], { file, line: lineOf(body, m.index) });
    }

    // split into prose and fenced code
    const fence = /```(\w*)\n([\s\S]*?)```/g;
    let prose = maskForProse(body);
    for (const m of body.matchAll(fence)) {
      prose = prose.slice(0, m.index) + m[0].replace(/[^\n]/g, ' ') + prose.slice(m.index + m[0].length);
      const lang = m[1];
      const skipRegion = [...body.matchAll(/<!-- validate:skip -->[\s\S]*?<!-- validate:end -->/g)].some((r) => m.index > r.index && m.index < r.index + r[0].length);
      if (skipRegion) continue;
      if (!['js', 'jsx', 'ts', 'tsx', 'typescript', 'javascript', 'html', 'vue', 'svelte'].includes(lang)) continue;
      const code = m[2];
      const codeStart = m.index + m[0].indexOf(code);
      const customCommands = new Set([...body.matchAll(/RegisterCommand\(\s*['"]([^'"]+)['"]/g)].map((x) => x[1]));
      const at = (i) => lineOf(body, codeStart + i);

      // toolbar buttons
      for (const tb of code.matchAll(/(?:toolbarButtons\w*|buttons|buildList\()\s*:?\s*\[([^\]]*)\]/g)) {
        for (const b of tb[1].matchAll(/['"]([^'"]+)['"]/g)) {
          const name = b[1];
          if (['|', '-'].includes(name) || commands.has(name) || customCommands.has(name) || allow.has(name)) continue;
          error(file, at(tb.index), `Toolbar button "${name}" is not a command in froala-editor ${froalaVersion}`);
        }
      }
      // events: keys of events: { ... } and events.on('x')
      for (const ev of code.matchAll(/\bevents\s*:\s*\{/g)) {
        const open = ev.index + ev[0].length - 1;
        for (const { key, index } of topLevelKeys(code, open)) {
          if (strings.has(key) || allow.has(key)) continue;
          error(file, at(index), `Event "${key}" does not exist in froala-editor ${froalaVersion}`);
        }
      }
      for (const ev of code.matchAll(/events\.on\(\s*['"]([^'"]+)['"]/g)) {
        if (!strings.has(ev[1]) && !allow.has(ev[1])) error(file, at(ev.index), `Event "${ev[1]}" does not exist in froala-editor ${froalaVersion}`);
      }
      // options: top-level keys of new FroalaEditor(x, {...}) and config/options objects
      const optionObjects = [
        ...code.matchAll(/new FroalaEditor\([^,{]+,\s*\{/g),
        ...code.matchAll(/\b(?:const|let|var)\s+(?:config|options|froalaConfig)\s*=\s*\{/g),
        ...code.matchAll(/\b(?:config|options)\s*=\s*\{\{/g),
      ];
      for (const o of optionObjects) {
        const open = o.index + o[0].length - 1;
        for (const { key, index } of topLevelKeys(code, open)) {
          if (invalidNames.has(key)) { error(file, at(index), `"${key}" is used as an option, but it is listed as intentionally invalid`); continue; }
          if (key === 'events' || existsInFroala(key) || allow.has(key)) continue;
          error(file, at(index), `Option "${key}" does not exist in froala-editor ${froalaVersion}`);
        }
      }

      // pluginsEnabled / pluginsDisabled values must be real plugin names (or plugins defined in this file)
      const customPlugins = new Set([...body.matchAll(/PLUGINS\.([A-Za-z_]\w*)\s*=/g)].map((x) => x[1]));
      for (const pe of code.matchAll(/plugins(?:Enabled|Disabled)\s*:\s*\[([^\]]*)\]/g)) {
        for (const v of pe[1].matchAll(/['"]([^'"]+)['"]/g)) {
          if (allPluginNames.has(v[1]) || customPlugins.has(v[1]) || allow.has(v[1])) continue;
          error(file, at(pe.index), `"${v[1]}" is not a plugin name in froala-editor ${froalaVersion} (see references/plugin-names.md)`);
        }
      }

      // editor.<module>.<method>( calls, through editor / this / getEditor()
      for (const mc of code.matchAll(/(?:\beditor|\bthis|getEditor\(\))\??\.([a-z][A-Za-z0-9_]*)\??\.([A-Za-z_][A-Za-z0-9_]*)\s*\(/g)) {
        const [, mod, method] = mc;
        if (customPlugins.has(mod) || allow.has(mod) || allow.has(`${mod}.${method}`)) continue;
        if (['$el', '$tb', '$box', 'opts', 'el'].includes(mod)) continue;
        if (invalidNames.has(`${mod}.${method}`)) { error(file, at(mc.index), `"${mod}.${method}()" is used in code, but it is listed as intentionally invalid`); continue; }
        if (!(tokens.has(mod) || wrapperTokens.has(mod)) || !(tokens.has(method) || wrapperTokens.has(method))) {
          error(file, at(mc.index), `"${mod}.${method}()" was not found in froala-editor ${froalaVersion}`);
        }
      }
      // any camelCase "key:" in the snippet (catches bare option lists such as `inlineSuggestions: false,`)
      const checked = new Set();
      for (const k of code.matchAll(/^[ \t]*([a-z][a-z0-9]*[A-Z][A-Za-z0-9]*)\s*:(?!:)/gm)) {
        const key = k[1];
        if (checked.has(key)) continue;
        checked.add(key);
        if (invalidNames.has(key)) { error(file, at(k.index), `"${key}" is used in code, but it is listed as intentionally invalid`); continue; }
        if (existsInFroala(key) || wrapperTokens.has(key) || allow.has(key)) continue;
        error(file, at(k.index), `"${key}" is not an option or identifier in froala-editor ${froalaVersion}`);
      }
    }

    // inline code in prose: `someOption`, `image.beforeUpload`, `editor.html.get()`
    for (const m of prose.matchAll(/`([^`\n]+)`/g)) {
      const t = m[1];
      const looksLikeApi = /^(?:editor\.|this\.)?[a-z][A-Za-z0-9]*(?:\.[A-Za-z_][A-Za-z0-9_]*)+(?:\(\))?$/.test(t) || // dotted
        /^[a-z][a-z0-9]*[A-Z][A-Za-z0-9]*(?:\(\))?$/.test(t) || // camelCase
        /^[a-z]+(?:_[a-z]+)+$/.test(t); // snake_case (plugin/button names)
      if (!looksLikeApi) continue;
      if (/\.(js|css|json|md|ts|tsx|jsx|mjs|vue|svelte|html|min)$/.test(t) || /^(?:js|css)\//.test(t)) continue;
      if (!identifierExists(t)) error(file, lineOf(body, m.index), `"${t}" was not found in froala-editor ${froalaVersion} or its wrappers. Fix it, or add it to scripts/validate-allowlist.json with a reason.`);
    }
  }
}

// 3. generated references
const generated = pluginNamesMarkdown();
for (const skill of PLUGIN_NAMES_TARGETS) {
  if (!skillDirs.includes(skill)) continue;
  const target = path.join(SKILLS_DIR, skill, 'references', 'plugin-names.md');
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (WRITE) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, generated);
  } else if (current !== generated) {
    error(target, 1, `Out of date for froala-editor ${froalaVersion}. Run: node scripts/validate-skills.mjs --froala ${froalaVersion} --write`);
  }
}

// 4. links (optional, warnings only)
if (CHECK_LINKS) {
  for (const [url, where] of links) {
    try {
      const res = await fetch(url, { method: 'GET', redirect: 'follow', headers: { 'user-agent': 'froala-skills-validator' } });
      if (res.status >= 400) warn(where.file, where.line, `Link returns HTTP ${res.status}: ${url}`);
    } catch (e) {
      warn(where.file, where.line, `Link could not be fetched: ${url} (${e.message})`);
    }
  }
}

// ---------- summary ----------
if (versionsSeen.size > 1) warn(null, 0, `Skills are verified against different versions: ${[...versionsSeen].join(', ')}`);
for (const w of warnings) console.log(`warning  ${w.file}${w.line ? `:${w.line}` : ''}  ${w.msg}`);
for (const e of errors) console.log(`ERROR    ${e.file}${e.line ? `:${e.line}` : ''}  ${e.msg}`);
console.log(`\n${skillDirs.length} skills, ${errors.length} error(s), ${warnings.length} warning(s)${WRITE ? ', references regenerated' : ''}`);
process.exit(errors.length ? 1 : 0);
